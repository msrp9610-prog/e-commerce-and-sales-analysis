-- Oracle star schema for CSE4005 e-commerce sales project.
-- Execute in your own schema. Natural keys are unique to simplify ETL lookups.

CREATE TABLE dim_date (
    date_key NUMBER(8) PRIMARY KEY, -- YYYYMMDD
    full_date DATE NOT NULL,
    day_number NUMBER(2),
    month_number NUMBER(2),
    month_name VARCHAR2(15),
    quarter_number NUMBER(1),
    year_number NUMBER(4),
    weekend_flag CHAR(1)
);

CREATE TABLE dim_product (
    product_key NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR2(40) NOT NULL UNIQUE
);

CREATE TABLE dim_region (
    region_key NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region_name VARCHAR2(40) NOT NULL UNIQUE
);

CREATE TABLE dim_customer_segment (
    segment_key NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    segment_name VARCHAR2(40) NOT NULL UNIQUE
);

CREATE TABLE fact_sales (
    sales_key NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id VARCHAR2(20) NOT NULL UNIQUE,
    date_key NUMBER(8) NOT NULL,
    product_key NUMBER NOT NULL,
    region_key NUMBER NOT NULL,
    segment_key NUMBER NOT NULL,
    units_sold NUMBER(8) NOT NULL,
    unit_price NUMBER(12,2) NOT NULL,
    discount_pct NUMBER(5,2) NOT NULL,
    sales_amount NUMBER(14,2) NOT NULL,
    CONSTRAINT fk_sales_date FOREIGN KEY (date_key) REFERENCES dim_date(date_key),
    CONSTRAINT fk_sales_product FOREIGN KEY (product_key) REFERENCES dim_product(product_key),
    CONSTRAINT fk_sales_region FOREIGN KEY (region_key) REFERENCES dim_region(region_key),
    CONSTRAINT fk_sales_segment FOREIGN KEY (segment_key) REFERENCES dim_customer_segment(segment_key)
);

CREATE INDEX idx_fact_sales_date ON fact_sales(date_key);
CREATE INDEX idx_fact_sales_product ON fact_sales(product_key);
CREATE INDEX idx_fact_sales_region ON fact_sales(region_key);
